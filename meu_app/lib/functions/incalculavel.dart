class Incalculavel {
  String ladoCalculado = "";
  String incalculavel = "";
  Incalculavel(ladoCalculado, incalculavel) {
    this.ladoCalculado = ladoCalculado;
    this.incalculavel = incalculavel;
  }
  String get ladoCalculadoGet {
    return this.ladoCalculado;
  }

  String get incalculavelGet => this.incalculavel;
}
